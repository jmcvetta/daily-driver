#!/usr/bin/env python3
"""Render `evals/RESULTS.md`, one row per committed eval record.

Reads every record under `evals/provenance/` -- never a run directory, which
is gitignored and exists only on the machine that ran it -- and writes the
whole page. `--check` writes nothing: it exits 1 when the committed page
differs from a fresh render, which is how `make check` catches a record
committed without its row.

USAGE

    python3 scripts/evals-render-results.py           # make evals-render-results
    python3 scripts/evals-render-results.py --check   # make check-evals-results
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PROVENANCE_DIR = ROOT / "evals" / "provenance"
DEFAULT_TARGET = ROOT / "evals" / "RESULTS.md"

NOT_RECORDED = "not recorded"

PREAMBLE = """\
# Eval results

Generated by `make evals-render-results` from the records in
[`provenance/`](provenance/). Do not edit it by hand: `make check` fails when
this page differs from a fresh render.

One row per committed record, oldest first.

- **Models served** is what the harness reported serving. Where it reported
  none -- Omp never does -- the requested model is shown, marked
  `(requested)`.
- **Judge** is who graded the semantic (`agent_judge`) criteria, apart from the
  subject: `omp-glm-5.3 (run-selected)` names the judge a run selected,
  `claude-code claude-sonnet-5 (task-pinned)` the Claude judge the task files
  pin, and `not recorded` a record that predates judge provenance. Records
  graded by different judges are different measurements.
- **Pass rate** counts replicates whose final status is `SUCCESS`. A
  model-classes replicate that reached its answer key counts as a failure.
- **Total price** is the record's summed per-replicate price, in USD, judge
  included. **Price per completed task** divides it by the replicates that
  passed. A record that carries no price shows `not recorded`, never `$0`.
  Schema-version-2 prices are shown for Claude Code only: on other harnesses
  that version recorded the judge's spend alone.
- **Wall time** is the whole run, `completed_at` minus `started_at`.
"""


def load_records(provenance_dir: Path) -> list[dict[str, Any]]:
    """Every committed record under `provenance_dir`, oldest run first."""
    records = [json.loads(path.read_text()) for path in sorted(provenance_dir.glob("*.json"))]
    records.sort(key=lambda record: (str(record.get("started_at", "")), str(record.get("run_id", ""))))
    return records


def models_served(record: dict[str, Any]) -> str:
    """Each distinct model the record's variants ran, served where reported."""
    names: list[str] = []
    for variant in record.get("variants", []):
        served = variant.get("model_served")
        name = served if served and served not in ("unknown", "unreported") else f"{variant.get('model_requested', 'unknown')} (requested)"
        if name not in names:
            names.append(name)
    return ", ".join(names) or "unknown"


def passed(attempt: dict[str, Any]) -> bool:
    """Whether one replicate passed: SUCCESS, and no answer-key contact."""
    status = attempt.get("final_status", attempt.get("status"))
    return status == "SUCCESS" and not attempt.get("answer_key_contact")


def total_price(record: dict[str, Any]) -> float | None:
    """The record's summed price in USD, or None where it carries none.

    Every case must carry a numeric cost; a partial sum would read as a whole
    one. Schema version 2 is trusted for Claude Code alone, the one harness
    that reported its own price before version 3 made the price required.
    Versions 3 and 4 require prices on every case.
    """
    cases = record.get("cases") or []
    version = record.get("schema_version")
    if not cases or version not in (2, 3, 4):
        return None
    if version == 2 and record.get("client", {}).get("name") != "claude-code":
        return None
    costs = [case.get("cost") for case in cases]
    if not all(isinstance(cost, (int, float)) and not isinstance(cost, bool) for cost in costs):
        return None
    return float(sum(costs))


def wall_time(record: dict[str, Any]) -> str:
    """The run's wall time, `completed_at` minus `started_at`, as `1h 02m 03s`."""
    try:
        elapsed = datetime.fromisoformat(record["completed_at"]) - datetime.fromisoformat(record["started_at"])
    except (KeyError, TypeError, ValueError):
        return NOT_RECORDED
    seconds = int(elapsed.total_seconds())
    if seconds < 0:
        return NOT_RECORDED
    hours, rest = divmod(seconds, 3600)
    minutes, seconds = divmod(rest, 60)
    return f"{hours}h {minutes:02d}m {seconds:02d}s" if hours else f"{minutes}m {seconds:02d}s"


def judge_text(record: dict[str, Any]) -> str:
    """Who graded the record's semantic criteria, or `not recorded` / `none`."""
    judge = record.get("judge")
    if not isinstance(judge, dict):
        return NOT_RECORDED
    if judge.get("selection") == "run-selected":
        return f"{judge.get('judge_id', judge.get('route'))} (run-selected)"
    requested = judge.get("model_requested")
    model = ", ".join(requested) if isinstance(requested, list) else str(requested)
    return f"{judge.get('route', 'claude-code')} {model} (task-pinned)"


def render_row(record: dict[str, Any]) -> str:
    """One markdown table row for `record`."""
    attempts = record.get("attempts") or []
    passes = sum(1 for attempt in attempts if passed(attempt))
    price = total_price(record)
    if price is None:
        price_text = per_task_text = NOT_RECORDED
    else:
        price_text = f"${price:.2f}"
        per_task_text = f"${price / passes:.2f}" if passes else "no task completed"
    cells = [
        str(record.get("started_at", ""))[:10],
        str(record.get("experiment_id", "unknown")),
        str(record.get("client", {}).get("name", "unknown")),
        models_served(record),
        judge_text(record),
        str(len(attempts)),
        f"{passes}/{len(attempts)}",
        price_text,
        per_task_text,
        wall_time(record),
    ]
    return "| " + " | ".join(cells) + " |"


def render_page(records: list[dict[str, Any]]) -> str:
    """The whole of `RESULTS.md` for `records`."""
    header = (
        "| Date | Experiment | Harness | Models served | Judge | Replicates | Pass rate "
        "| Total price | Price per completed task | Wall time |"
    )
    separator = "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"
    rows = [render_row(record) for record in records]
    return PREAMBLE + "\n" + "\n".join([header, separator, *rows]) + "\n"


def parse_args() -> argparse.Namespace:
    """Parse renderer command-line arguments."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--provenance-dir", type=Path, default=DEFAULT_PROVENANCE_DIR)
    parser.add_argument("--target", type=Path, default=DEFAULT_TARGET)
    parser.add_argument("--check", action="store_true", help="fail when the target is stale; write nothing")
    return parser.parse_args()


def main() -> int:
    """Render the results page, or check that the committed one is current."""
    args = parse_args()
    page = render_page(load_records(args.provenance_dir))
    if args.check:
        current = args.target.read_text() if args.target.is_file() else ""
        if current != page:
            print(f"{args.target} is stale; run `make evals-render-results` and commit it", file=sys.stderr)
            return 1
        return 0
    args.target.write_text(page)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
